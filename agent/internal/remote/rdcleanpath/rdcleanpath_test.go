var deadbeef = []byte{0xDE, 0xAD, 0xBE, 0xFF}

func TestEncodeMatchesIronRDP(t *testing.T) {
	cases := map[string]struct {
		pdu  PDU
		want []byte
	}{
		"request":    {NewRequest(deadbeef, "destination", "proxy auth", "PCB"), requestDER},
		"response":   {NewResponse("192.168.7.95", deadbeef, [][]byte{deadbeef, deadbeef, deadbeef}), responseDER},
		"http error": {NewHTTPError(500), httpErrorDER},
		"tls error":  {NewTLSError(48), tlsErrorDER},
	}
	for name, c := range cases {
		got, err := c.pdu.Encode()
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if !bytes.Equal(got, c.want) {
			t.Fatalf("%s:\n got % X\nwant % X", name, got, c.want)
		}
	}
}

func TestDecodeRequest(t *testing.T) {
	p, err := DecodeRequest(requestDER)
	if err != nil {
		t.Fatal(err)
	}
	if p.Destination != "destination" || p.ProxyAuth != "proxy auth" || p.PreconnectionBlob != "PCB" || !bytes.Equal(p.X224ConnectionPDU, deadbeef) {
		t.Fatalf("pedido lido errado: %+v", p)
	}
	if _, err := DecodeRequest(responseDER); err == nil {
		t.Fatal("resposta aceita como pedido")
	}
	r, err := Decode(responseDER)
	if err != nil || r.ServerAddr != "192.168.7.95" || len(r.ServerCertChain) != 3 {
		t.Fatalf("resposta lida errada: %+v %v", r, err)
	}
	e, err := Decode(httpErrorDER)
	if err != nil || e.Error.Code != GeneralError || e.Error.HTTPStatusCode != 500 {
		t.Fatalf("erro lido errado: %+v %v", e, err)
	}
}

func TestDecodeRejectsGarbage(t *testing.T) {
	for _, in := range [][]byte{nil, {0x30}, append(append([]byte{}, requestDER...), 0x00), {0x30, 0x05, 0xA0, 0x03, 0x02, 0x01, 0x01}} {
		if _, err := Decode(in); err == nil {
			t.Fatalf("aceitou % X", in)
		}
	}
}
